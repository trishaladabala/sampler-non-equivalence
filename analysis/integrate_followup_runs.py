#!/usr/bin/env python3
"""Integrates completed follow-up experiment artifacts (E1-E4) into local analysis and LaTeX tables.

Usage:
  # After downloading p5_non_identifiability_artifacts.zip from Google Drive:
  python3 analysis/integrate_followup_runs.py --zip /path/to/p5_non_identifiability_artifacts.zip

  # Or if already extracted under runs/:
  python3 analysis/integrate_followup_runs.py
"""

from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parent.parent
RUNS_DIR = ROOT / "content" / "drive" / "MyDrive" / "elf_research" / "runs"
TABLES_DIR = ROOT / "tables"


def _fmt_opt(val: float | None, fmt: str) -> str:
    if val is None or (isinstance(val, float) and (math.isnan(val) or math.isinf(val))):
        return "---"
    return format(float(val), fmt)


def cleanup_nested_artifacts() -> None:
    """Remove any accidental nested extraction or macOS resource-fork folders."""
    for stray in ("p5_non_identifiability_artifacts", "p6_followup_artifacts", "__MACOSX"):
        p = RUNS_DIR / stray
        if p.exists():
            shutil.rmtree(p)
            print(f"[integrate] Removed stray nested folder: {p}")


def extract_zip_if_provided(zip_path: Path) -> None:
    if not zip_path.is_file():
        raise FileNotFoundError(f"Artifact zip not found: {zip_path}")
    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    cleanup_nested_artifacts()
    extracted = 0
    skipped = 0
    with zipfile.ZipFile(zip_path, "r") as zf:
        for member in zf.infolist():
            name = member.filename
            if "__MACOSX" in name or Path(name).name.startswith("._"):
                continue
            parts = Path(name).parts
            if parts and parts[0] in ("p5_non_identifiability_artifacts", "p6_followup_artifacts"):
                parts = parts[1:]
            if not parts:
                continue
            rel_path = Path(*parts)
            dest = RUNS_DIR / rel_path
            if member.is_dir() or name.endswith("/"):
                dest.mkdir(parents=True, exist_ok=True)
            else:
                if dest.exists():
                    skipped += 1
                    continue
                dest.parent.mkdir(parents=True, exist_ok=True)
                with zf.open(member, "r") as src, open(dest, "wb") as dst:
                    shutil.copyfileobj(src, dst)
                extracted += 1
    print(f"[integrate] Extracted {extracted} new files (skipped {skipped} existing files) from {zip_path} -> {RUNS_DIR}")


def write_e1_latex_table(e1_json_path: Path, out_tex_path: Path) -> None:
    # Aggregate all ELF-M 64-step runs directly from RUNS_DIR (including P6 2x2x5 factorial cells)
    by_cell: dict[tuple[float, float], list[dict]] = {}
    for summary_path in sorted(RUNS_DIR.glob("*/summary.json")):
        rid = summary_path.parent.name
        if not rid.startswith(("p4_elfm_s64_", "p5_elfm_s64_")):
            continue
        rec = json.loads(summary_path.read_text(encoding="utf-8"))
        ext_path = summary_path.parent / "extended_metrics.json"
        if ext_path.is_file():
            rec.update(json.loads(ext_path.read_text(encoding="utf-8")))
        key = (float(rec["sc_cfg"]), float(rec["gamma"]))
        by_cell.setdefault(key, []).append(rec)

    if not by_cell:
        return

    def _mean_key(rlist: list[dict], k: str) -> float | None:
        vals = [float(x[k]) for x in rlist if k in x and x[k] is not None]
        return sum(vals) / len(vals) if vals else None

    lines = [
        "% AUTO-GENERATED by analysis/integrate_followup_runs.py -- do not edit",
        r"\begin{tabular}{cccccccccccc}",
        r"\toprule",
        r"SC-CFG & $\gamma$ & Seeds & Gen-PPL & $H_{\text{ps}}$ & $H_{\text{pool}}$ & $\mathrm{JSD}_{\text{inter}}$ & rep-4 (\%) & distinct-2 & Self-BLEU & JCD (bpb) & MAUVE \\",
        r"\midrule",
    ]
    for (sc, gm), rlist in sorted(by_cell.items()):
        n_s = len(rlist)
        ppl = _mean_key(rlist, "gen_ppl")
        ent = _mean_key(rlist, "entropy")
        h_pool = _mean_key(rlist, "h_pool")
        jsd = _mean_key(rlist, "jsd_inter_sample")
        rep4 = _mean_key(rlist, "rep4")
        d2 = _mean_key(rlist, "distinct2")
        sbleu = _mean_key(rlist, "self_bleu")
        jcd = _mean_key(rlist, "jcd_bits_per_byte")
        mv = _mean_key(rlist, "mauve")
        lines.append(
            f"{sc:.1f} & {gm:.2f} & {n_s} & {ppl:.2f} & "
            f"{ent:.3f} & {_fmt_opt(h_pool, '.3f')} & "
            f"{_fmt_opt(jsd, '.3f')} & "
            f"{100.0 * rep4:.2f} & {d2:.3f} & "
            f"{_fmt_opt(sbleu, '.2f')} & "
            f"{_fmt_opt(jcd, '.4f')} & {mv:.3f} \\\\"
        )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
    ]
    out_tex_path.parent.mkdir(parents=True, exist_ok=True)
    out_tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[integrate] Wrote {out_tex_path}")


def write_e2_latex_table(e2_json_path: Path, out_tex_path: Path, cp_stats_path: Path | None = None) -> None:
    with open(e2_json_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    pairs = data.get("pair_reports", [])
    if not pairs:
        return

    lines = [
        "% AUTO-GENERATED by analysis/integrate_followup_runs.py -- do not edit",
        r"\begin{tabular}{llcccccccc}",
        r"\toprule",
        r"Tier & Pair $(s_1,\gamma_1)\to(s_2,\gamma_2)$ & $\Delta H_{\text{ps}}$ & $\Delta H_{\text{pool}}$ & $\Delta\mathrm{JSD}_{\text{inter}}$ & $\Delta$rep-4 (pp) & $\Delta\text{dist-2}_{\text{cross}}$ & $\Delta$Self-BLEU & $\Delta$JCD (bpb) & $\Delta$MAUVE \\",
        r"\midrule",
    ]
    for pr in pairs:
        lines.append(
            f"{pr['tier']} & \\texttt{{{pr['low_path']}}} $\\to$ \\texttt{{{pr['high_path']}}} & "
            f"${pr['delta_H_ps']:+.4f}$ & ${pr['delta_H_pool']:+.4f}$ & "
            f"${pr['delta_jsd_inter']:+.4f}$ & ${pr['delta_rep4_pp']:+.2f}$ & "
            f"${pr['delta_cross_distinct2']:+.4f}$ & ${pr['delta_self_bleu']:+.2f}$ & "
            f"${pr['delta_jcd_bpb']:+.4f}$ & ${pr['delta_mauve']:+.3f}$ \\\\"
        )
    if cp_stats_path and cp_stats_path.is_file():
        cp = json.loads(cp_stats_path.read_text(encoding="utf-8"))
        ref_pairs = [
            rp for rp in cp.get("elfb_refinement_pairs", [])
            if abs(rp["d_ent"]) <= 0.010 and rp["ci_overlap_ppl"] > 0
        ]
        if ref_pairs:
            lines.append(r"\midrule")
            for rp in ref_pairs:
                low_s = f"SC={rp['sc1']}, gamma={rp['g1']:.2f}"
                high_s = f"SC={rp['sc2']}, gamma={rp['g2']:.2f}"
                lines.append(
                    f"Refined & \\texttt{{{low_s}}} $\\to$ \\texttt{{{high_s}}} & "
                    f"${rp['d_ent']:+.4f}$ & ${rp['d_h_pool']:+.4f}$ & "
                    f"${rp['d_jsd']:+.4f}$ & ${rp['d_rep4_pp']:+.2f}$ & "
                    f"${rp['d_d2']:+.4f}$ & ${rp['d_self_bleu']:+.2f}$ & "
                    f"${rp['d_jcd_bpb']:+.4f}$ & ${rp['d_mauve']:+.3f}$ \\\\"
                )
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
    ]
    out_tex_path.parent.mkdir(parents=True, exist_ok=True)
    out_tex_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[integrate] Wrote {out_tex_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Integrate follow-up experiment results (E1-E4).")
    parser.add_argument("--zip", type=str, default=None, help="Path to p5_non_identifiability_artifacts.zip")
    args = parser.parse_args()

    if args.zip:
        extract_zip_if_provided(Path(args.zip))
    else:
        cleanup_nested_artifacts()

    # Refresh results_db.csv, control-path stats, ACL 2027 stats, and figures/tables
    for script in (
        "analysis/collect_runs.py",
        "analysis/frontier_analysis.py",
        "analysis/control_path_study.py",
        "analysis/statistical_reanalysis.py",
        "analysis/make_figures_tables.py",
    ):
        sp = ROOT / script
        if sp.is_file():
            subprocess.run([sys.executable, str(sp)], check=True)

    p5_dir = RUNS_DIR / "p5_non_identifiability"
    e1_json = p5_dir / "e1_elfm_factorial" / "e1_elfm_results.json"
    e2_json = p5_dir / "e2_matched_rescore" / "e2_matched_rescore_results.json"
    cp_stats = ROOT / "analysis" / "out" / "control_path_stats.json"

    if e1_json.is_file():
        write_e1_latex_table(e1_json, TABLES_DIR / "tab_elfm_factorial.tex")
    else:
        print(f"[integrate] E1 results not yet present at {e1_json}")

    if e2_json.is_file():
        write_e2_latex_table(e2_json, TABLES_DIR / "tab_jcd_selfbleu_pairs.tex", cp_stats)
    else:
        print(f"[integrate] E2 results not yet present at {e2_json}")


if __name__ == "__main__":
    main()
