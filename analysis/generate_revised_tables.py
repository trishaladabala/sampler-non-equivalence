def build_tab_iso_frontier_validation(iso_stats: dict, stats: dict) -> str:
    """
    Builds the out-of-sample validation table comparing integrated iso-frontier
    predictions (fitted on Stage-1 response surfaces) against observed pilot differences
    (evaluated on disjoint held-out seeds 201-205 with paired seed-level 95% CIs, df=4).
    """
    t_crit_4 = 2.7764451052
    c_pairs = stats["phase2_equivalence"]["confirmatory_pairs_c1_c2_c3"]
    pair_key_map = {
        "C1": "C1_ELFB_SC2_vs_SC1",
        "C2": "C2_ELFB_SC3_vs_SC1",
        "C3": "C3_ELFB_SC4_vs_SC1",
    }

    lines = [
        r"\begingroup",
        r"\small",
        r"\setlength{\tabcolsep}{3.6pt}",
        r"\renewcommand{\arraystretch}{0.95}",
        r"\begin{tabular}{llcccc}",
        r"\toprule",
        r"Pair & Metric & Predicted $\Delta_{\mathrm{pred}} = \int_{\mathcal{C}} \kappa_m d\ell$ & Observed $\Delta_{\mathrm{obs}}$ [95\% Paired CI] (Seeds 201--205) & Discrepancy & Rel.\ Error \\",
        r"\midrule",
    ]

    pair_meta = [
        ("C1", r"\textbf{C1}: $(1.0, 1.346) \to (2.0, 1.000)$"),
        ("C2", r"\textbf{C2}: $(1.0, 1.547) \to (3.0, 1.000)$"),
        ("C3", r"\textbf{C3}: $(1.0, 1.651) \to (4.0, 1.000)$"),
    ]

    metric_meta = [
        ("rep4", "rep-4", "{:+.4f}"),
        ("jsd_inter_sample", r"$\mathrm{JSD}_\pi$ (nats)", "{:+.4f}"),
        ("mauve", "MAUVE", "{:+.3f}"),
    ]

    for p_idx, (pk, plab) in enumerate(pair_meta):
        p_data = iso_stats[pk]
        arc_len = p_data["arc_length"]
        oos = p_data["out_of_sample_validation"]
        sec_stats = c_pairs[pair_key_map[pk]]["secondary_metrics"]

        for m_idx, (mk, mlab, fmt) in enumerate(metric_meta):
            m_oos = oos[mk]
            pred = m_oos["predicted_delta_integrated"]
            obs = m_oos["held_out_measured_delta"]
            disc = m_oos["discrepancy"]
            rel_err = (disc / abs(obs)) * 100.0 if abs(obs) > 0 else 0.0
            se_p = sec_stats[mk]["se_paired"]
            ci_p = (obs - t_crit_4 * se_p, obs + t_crit_4 * se_p)

            first_col = plab if m_idx == 0 else (f"$(\\Delta\\ell = {arc_len:.2f})$" if m_idx == 1 else "")

            p_str = fmt.format(pred)
            o_str = f"${fmt.format(obs)}$ $[{fmt.format(ci_p[0])},\\,{fmt.format(ci_p[1])}]$"
            d_str = fmt.format(disc)
            r_str = f"{rel_err:+.1f}\\%"

            lines.append(f"{first_col} & {mlab} & ${p_str}$ & {o_str} & ${d_str}$ & {r_str} \\\\")

        if p_idx < len(pair_meta) - 1:
            lines.append(r"\midrule")

    lines.extend([
        r"\midrule",
        r"\multicolumn{6}{@{}p{\textwidth}@{}}{\footnotesize Out-of-sample prediction: \texttt{rep-4} and MAUVE response surfaces fitted on the 56-run Stage-1 ELF-B grid (seeds $\{0, 1\}$); $\mathrm{JSD}_\pi$ response surface fitted on the 40-run Stage-1 ELF-B evaluation across 11 operating points (seeds $0\text{--}4$, quadratic polynomial $R^2=0.980$, with two synthetic residual-split pseudo-replicates $\pm 0.5\,\mathrm{SD}_{\mathrm{res}}$ stored in \path{iso_frontier_sensitivity.json}). Observed differences $\Delta_{\mathrm{obs}}$ evaluated on seed-disjoint held-out pilot seeds $201\text{--}205$ ($M=1{,}000$/seed, paired seed-level CRN 95\% CIs with $df=4$); operating points C1--C3 were selected on the same Stage-1 response surface.} \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\endgroup",
        "",
    ])
    return "\n".join(lines)


def update_tab_interventions() -> None:
    path = os.path.join(TAB_DIR, "tab_interventions.tex")
    if os.path.exists(path):
        txt = open(path).read()
        txt_new = txt.replace("Pareto-dominated", r"2D $(\text{PPL},H_{\mathrm{ps}})$-dominated")
        txt_new = txt_new.replace(
            r"\multicolumn{9}{l}{\footnotesize " + PARAM_FOOTNOTE + r"} \\",
            r"\multicolumn{9}{@{}p{\linewidth}@{}}{\footnotesize " + PARAM_FOOTNOTE + r"} \\"
        )
        if PARAM_FOOTNOTE not in txt_new:
            txt_new = txt_new.replace(
                r"\bottomrule",
                r"\midrule" + "\n" + r"\multicolumn{9}{@{}p{\linewidth}@{}}{\footnotesize " + PARAM_FOOTNOTE + r"} \\" + "\n" + r"\bottomrule"
            )
        with open(path, "w") as f:
            f.write(txt_new)
        print(f"[updated] {path}")


