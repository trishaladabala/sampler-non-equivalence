def write_tex(filename: str, content: str) -> None:
    path = os.path.join(TAB_DIR, filename)
    with open(path, "w") as f:
        f.write("% AUTO-GENERATED by analysis/generate_revised_tables.py -- do not edit manually\n")
        f.write(content)
    print(f"[wrote] {path} ({len(content)} bytes)")


def fmt_p(p: float) -> str:
    if p < 1e-4:
        exp = int(f"{p:.2e}".split("e")[1])
        mant = float(f"{p:.2e}".split("e")[0])
        return f"${mant:.2f}\\!\\times\\!10^{{{exp}}}$"
    return f"${p:.4f}$"


def fmt_p_bare(p: float, dec: int = 3) -> str:
    threshold = 10.0 ** (-dec)
    if p < threshold:
        exp = int(f"{p:.1e}".split("e")[1])
        mant = float(f"{p:.1e}".split("e")[0])
        return f"{mant:.1f}\\!\\times\\!10^{{{exp}}}"
    return f"{p:.{dec}f}"


